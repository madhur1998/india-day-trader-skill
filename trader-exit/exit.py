#!/usr/bin/env python3
"""Exit Planner for trader-exit: sets the stop and the target BEFORE you
enter, so you know when to get out. NSE, India time, rupees. Standard library
only. Long side only. It never places an order.

    python3 exit.py plan                                    # from trader/entry.json: or-mid stop, 2R target
    python3 exit.py plan --stop or-mid --target 2R --write  # the reel: stop 1,190.90, target 1,217.00
    python3 exit.py plan --symbol RELIANCE --entry 1199.6 --or-high 1194.8 --or-low 1187
    python3 exit.py plan --stop atr:1.5 --offline RELIANCE.json   # ATR needs the session's bars
    python3 exit.py plan --symbol SBIN --entry 958 --setup level --stop pct:1
    python3 exit.py show                                    # the current trader/plan.json

Stops (a long's stop rounds DOWN onto the NSE tick grid, away from the entry):
  or-mid     the opening-range midpoint (the default for an orb entry)
  or-low     the opening-range low
  price:X    your price
  pct:X      X percent under the entry
  atr:K      K times the 14-bar ATR under the entry, on the session's bars up
             to the entry bar (--offline FILE or Yahoo). With fewer than 14
             bars by then it averages all of them and says so.
  A level setup has no opening-range default: give a stop.

Targets (round UP onto the tick grid):
  2R (default), 1R, 1.5R ...   entry + R x risk, where risk = entry - stop
  price:X                      your price

The tick is NSE's for the entry price (0.01 under Rs 250, 0.05 to Rs 1,000,
0.10 to Rs 5,000 ...) or "tick_size" in trader/config.json.

Refused, with the reason: a stop at or above the entry, a target at or below
it, a risk under 0.05% of the price (too tight to survive the spread), a risk
where the round-trip charges a share at the stop are more than 25% of it (too
tight to survive the charges), an entry.json that has not triggered (unless
you give --entry), a short (this pack plans longs only).

Charges a share are the intraday (MIS) rates in CHARGES, merged with
"charges" in the config, with brokerage at its percentage: the most a share
can cost, exact for orders up to about Rs 66,667 a side (above that Zerodha's
Rs 20 cap makes it cheaper). STT and stamp duty are not rounded to the rupee
here, so the number does not depend on the quantity. plan.json carries the
rates ("charges_rates") and the tick ("tick_size") so trader-budget, the Time
Machine and Price Alerts work out the rupees for their quantity, plus
"reward_risk_net": (reward - charges at the target) / (risk + charges at the
stop), a share.

flat_by (default 15:10, or "flat_by" in trader/config.json): out by then, win
or lose, before the broker's MIS auto square-off (about 15:20). On a Muhurat
evening session it moves with the close. "min_reward_risk" in the config
(default 1.0) only warns here (net of charges unless "count_charges" is
false); trader-risk enforces it. A config key ending in _usd is an error
naming its _inr name.

A stop is a plan, not a guarantee: a gap or a fast market can fill past it.
Exit codes: plan 0 = a plan, 1 = refused or an error. show 0 = a plan exists.
"""

