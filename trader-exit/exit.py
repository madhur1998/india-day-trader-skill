def parse_hhmm(text, what):
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*$", str(text))
    if not m or int(m.group(1)) > 23 or int(m.group(2)) > 59:
        raise PlanError("%s wants an India time like 15:10, not %r" % (what, text))
    return datetime.time(int(m.group(1)), int(m.group(2)))


def parse_clock(text, what):
    """9:45 AM, 09:45, 1:05 PM -> time."""
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*([AaPp][Mm])?\s*$", str(text))
    if not m:
        raise PlanError("%s wants a time like 9:45 AM, not %r" % (what, text))
    h, mi = int(m.group(1)), int(m.group(2))
    if m.group(3):
        if not 1 <= h <= 12:
            raise PlanError("%s wants a time like 9:45 AM, not %r" % (what, text))
        h = h % 12 + (12 if m.group(3).upper() == "PM" else 0)
    if h > 23 or mi > 59:
        raise PlanError("%s wants a time like 9:45 AM, not %r" % (what, text))
    return datetime.time(h, mi)


def hm(t):
    return "%02d:%02d" % (t.hour, t.minute)


def ampm(t):
    h = t.hour % 12 or 12
    return "%d:%02d %s" % (h, t.minute, "AM" if t.hour < 12 else "PM")


# ---------------------------------------------------------------- money math (Decimal, on the tick grid)

def D(x, what="a number"):
    try:
        if isinstance(x, float):
            return Decimal(repr(x))
        t = str(x).strip().replace(",", "")
        if t.lower().startswith("rs"):
            t = t[2:].strip()
        return Decimal(t.lstrip("₹"))
    except (InvalidOperation, ValueError):
        raise PlanError("%s is not a number: %r" % (what, x))


def to_paisa(x):
    """Round half up to the paisa (for ratios and per-share charges)."""
    return D(x).quantize(PAISA, rounding=ROUND_HALF_UP)


def on_tick(x, direction, tick):
    """A price onto the tick grid as a Decimal: down for a stop, up for a target."""
    return D(round_tick(float(x), direction, float(tick)))


def money(x):
    return inr(float(x))


def num(x):
    """1, 1.5, 1190.9: a Decimal without trailing zeros."""
    return format(D(x).normalize(), "f")


def ratio(x):
    """reward:risk for people: 1.0, 1.5, 1.37."""
    s = "%.2f" % float(x)
    return s[:-1] if s.endswith("0") else s


def per_share_charges(buy, sell, rates):
    """Round-trip charges a share, buying at `buy` and selling at `sell`: the
    same parts as charges() in tests/_nse.py, with brokerage at its percentage (no Rs 20 cap)
    and STT and stamp duty unrounded, so it does not depend on the quantity."""
    r = {k: D(v) for k, v in rates.items()}
    b, s = D(buy), D(sell)
    hundred = Decimal(100)
    brokerage = (b + s) * r["brokerage_pct"] / hundred
    stt = s * r["stt_sell_pct"] / hundred
    exchange = (b + s) * r["exchange_pct"] / hundred
    sebi = (b + s) * r["sebi_pct"] / hundred
    stamp = b * r["stamp_buy_pct"] / hundred
    gst = (brokerage + exchange + sebi) * r["gst_pct"] / hundred
    return brokerage + stt + exchange + sebi + stamp + gst


WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}


def parse_stop(text):
    t = str(text).strip().lower()
    if t in ("or-mid", "or_mid", "mid", "or-midpoint"):
        return "or_mid", None
    if t in ("or-low", "or_low", "low"):
        return "or_low", None
    m = re.match(r"^(price|pct|atr):\s*(?:rs\.?\s*)?([0-9][0-9,]*\.?[0-9]*)$", t)
    if not m:
        raise PlanError("--stop is or-mid, or-low, price:X, pct:X or atr:K (got %r)" % text)
    kind, val = m.group(1), D(m.group(2), "--stop")
    if val <= 0:
        raise PlanError("--stop %s needs a number above 0" % kind)
    if kind == "pct" and val >= 100:
        raise PlanError("--stop pct:X needs X under 100")
    return kind, val


def parse_target(text):
    t = str(text).strip()
    m = re.match(r"^([0-9]*\.?[0-9]+)\s*[Rr]$", t)
    if m:
        r = D(m.group(1), "--target")
        if r <= 0:
            raise PlanError("--target needs an R multiple above 0, like 1R or 2R")
        return "r", r
    m = re.match(r"^price:\s*(?:rs\.?\s*)?([0-9][0-9,]*\.?[0-9]*)$", t.lower())
    if m:
        return "price", D(m.group(1), "--target")
    raise PlanError("--target is 2R, 1R, 1.5R ... or price:X (got %r)" % text)


def r_label(r):
    n = int(r) if r == r.to_integral_value() else None
    return "%sR (%s times the risk)" % (num(r), WORDS.get(n, num(r)))


def compute(entry, stop_rule, stop_param, target_rule, target_param, or_high=None, or_low=None,
            atr=None, atr_bars=None, tick=None, rates=None):
    """The stop, the target and the risk, on the tick grid. Raises PlanError with the reason."""
    if D(entry) <= 0:
        raise PlanError("the entry price must be above Rs 0")
    tk = D(tick if tick else tick_size(float(D(entry))))
    rates = dict(CHARGES, **(rates or {}))
    e = on_tick(entry, "nearest", tk)
    detail = ""
    if stop_rule in ("or_mid", "or_low"):
        if or_high is None or or_low is None:
            raise PlanError("an %s stop needs the opening range (--or-high and --or-low)" % stop_rule.replace("_", "-"))
        oh, ol = on_tick(or_high, "nearest", tk), on_tick(or_low, "nearest", tk)
        if oh <= ol:
            raise PlanError("the opening-range high %s must be above its low %s" % (money(oh), money(ol)))
        if stop_rule == "or_mid":
            raw = (oh + ol) / 2
            label = "opening-range midpoint"
            detail = "(%s + %s) / 2 = %s" % (money(oh), money(ol), num(raw))
        else:
            raw, label = ol, "opening-range low"
    elif stop_rule == "price":
        raw, label = stop_param, "your price"
    elif stop_rule == "pct":
        raw = e * (1 - stop_param / 100)
        label = "%s%% under the entry" % num(stop_param)
        detail = "%s x (1 - %s%%) = %s" % (money(e), num(stop_param), num(raw))
    elif stop_rule == "atr":
        if atr is None:
            raise PlanError("an atr stop needs the session's bars")
        a = D(round(atr, 6))
        raw = e - stop_param * a
        label = "%s x ATR(%d) under the entry" % (num(stop_param), atr_bars)
        detail = "ATR %s over the %d bars to the entry%s" % (
            num(a.quantize(Decimal("0.0001"))), atr_bars, " (fewer than 14 so far)" if atr_bars < ATR_BARS else "")
    else:
        raise PlanError("unknown stop rule %r" % stop_rule)
    stop = on_tick(raw, "down", tk)
    if stop != D(raw):
        down = "rounded down to the %s tick" % money(tk)
        detail = (detail + ", " + down) if detail else "%s %s" % (num(raw), down)
    if stop >= e:
        raise PlanError("the stop %s (%s) is at or above the entry %s: a long's stop goes under the entry"
                        % (money(stop), label, money(e)))
    if stop <= 0:
        raise PlanError("the stop works out to %s: pick a stop above Rs 0" % money(stop))
    risk = e - stop
    floor_risk = e * MIN_RISK_PCT / 100
    if risk < floor_risk:
        raise PlanError("the stop is %s under the entry, less than 0.05%% of the price (%s on %s): too tight to "
                        "survive the spread, normal wiggle would stop you out. Widen it."
                        % (money(risk), money(to_paisa(floor_risk)), money(e)))
    cost_stop = per_share_charges(e, stop, rates)
    if cost_stop * 100 > risk * MAX_CHARGES_PCT:
        raise PlanError("round-trip charges of about %s a share (brokerage, STT, exchange, SEBI, stamp duty, GST) "
                        "are %s%% of the %s risk a share, more than %s%%: too tight to survive the charges, they "
                        "eat the trade. Widen the stop to at least %s under the entry."
                        % (money(to_paisa(cost_stop)), num(to_paisa(cost_stop / risk * 100)), money(risk),
                           num(MAX_CHARGES_PCT), money(to_paisa(cost_stop * 100 / MAX_CHARGES_PCT))))
    if target_rule == "r":
        target = on_tick(e + target_param * risk, "up", tk)
        t_label = r_label(target_param)
    else:
        target = on_tick(target_param, "up", tk)
        t_label = None
    if target <= e:
        raise PlanError("the target %s is at or below the entry %s: a long's target goes above it"
                        % (money(target), money(e)))
    rr = to_paisa((target - e) / risk)
    if t_label is None:
        t_label = "your price (%sR)" % ratio(rr)
    cost_target = per_share_charges(e, target, rates)
    rr_net = to_paisa((target - e - cost_target) / (risk + cost_stop))
    return {"entry": e, "stop": stop, "stop_label": label, "stop_detail": detail, "target": target,
            "target_r": target_param if target_rule == "r" else rr, "target_label": t_label,
            "risk": risk, "reward_risk": rr, "tick": tk, "rates": rates,
            "cost_stop": to_paisa(cost_stop), "cost_target": to_paisa(cost_target), "reward_risk_net": rr_net}


